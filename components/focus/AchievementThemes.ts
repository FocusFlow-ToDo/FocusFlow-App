export function getGlobalTheme(badgeProps: any): AchievementTheme {
  let colorStr = "";
  
  if (typeof badgeProps === "string") {
    colorStr = badgeProps.toLowerCase();
  } else if (badgeProps) {
    if (badgeProps.color) {
       colorStr = badgeProps.color.toLowerCase();
    } else if (badgeProps.name && COLOR_MAP[badgeProps.name]) {
       colorStr = COLOR_MAP[badgeProps.name];
    } else {
       colorStr = (badgeProps.suffix || badgeProps.label || "amber").toLowerCase();
    }
  }

  for (const c of Object.keys(THEME_RECORD)) {
    if (colorStr.includes(c)) return THEME_RECORD[c];
  }

  if (colorStr.includes("görev") || colorStr.includes("blue")) return THEME_RECORD.blue;
  if (colorStr.includes("alt") || colorStr.includes("emerald")) return THEME_RECORD.emerald;
  if (colorStr.includes("dk") || colorStr.includes("cyan")) return THEME_RECORD.cyan;
  if (colorStr.includes("gün") || colorStr.includes("rose")) return THEME_RECORD.rose;

  return THEME_RECORD.amber;
}
